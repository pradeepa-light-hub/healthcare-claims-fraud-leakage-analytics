USE ROLE ACCOUNTADMIN;
USE WAREHOUSE HEALTHCARE_WH;
USE DATABASE HEALTHCARE;

CREATE SCHEMA IF NOT EXISTS HEALTHCARE.STAGING;

CREATE OR REPLACE VIEW HEALTHCARE.STAGING.STG_CLAIMS AS
SELECT
     TRIM(CLAIM_ID) AS CLAIM_ID,
     TRIM(PATIENT_ID) AS PATIENT_ID,
     TRIM(POLICY_NUMBER) AS POLICY_NUMBER,
     TRIM(INSURANCE_PLAN) AS INSURANCE_PLAN,
     TRIM(PROVIDER_NAME) AS PROVIDER_NAME,
     UPPER(TRIM(DIAGNOSIS_CODE)) AS DIAGNOSIS_CODE,
     CASE UPPER(TRIM(DIAGNOSIS_CODE))
      WHEN 'E11.9' THEN 'Type 2 Diabetes'
      WHEN 'I10' THEN 'Essential Hypertension'
      WHEN 'J45.909' THEN 'Unspecified Asthma'
      WHEN 'M25.56' THEN 'Pain in Knee'
      WHEN 'R07.9' THEN 'Chest Pain'
      WHEN 'Z00.00' THEN 'Routine General Exam'
      ELSE 'Other Diagnosis'
     END AS DIAGNOSIS_DESC,
    TRIM(PROCEDURE_CODE) AS PROCEDURE_CODE,
    CASE TRIM(PROCEDURE_CODE)
        WHEN '36415' THEN 'Routine Venipuncture (Blood Draw)'
        WHEN '99213' THEN 'Outpatient Office Visit'
        WHEN '99283' THEN 'Emergency Dept Visit'
        WHEN '74177' THEN 'CT Abdomen & Pelvis'
        WHEN '27447' THEN 'Total Knee Arthroplasty (Surgery)'
        ELSE 'Other Procedure'
    END AS PROCEDURE_DESC,
    TRY_TO_NUMBER(CHARGE_AMOUNT, 10, 2) AS CHARGE_AMOUNT,
    TRY_TO_DATE(DATE_OF_SERVICE) AS DATE_OF_SERVICE,
    TRY_TO_DATE(SUBMITTED_DATE) AS SUBMITTED_DATE,
    DATEDIFF(DAY, TRY_TO_DATE(DATE_OF_SERVICE), TRY_TO_DATE(SUBMITTED_DATE)) AS SUBMISSION_LAG_DAYS
FROM HEALTHCARE.RAW.RAW_CLAIMS
WHERE CLAIM_ID IS NOT NULL;

-- Sanity check: Verify row count and preview clean data
SELECT COUNT(*) AS CLEAN_STAGING_ROWS FROM HEALTHCARE.STAGING.STG_CLAIMS;
SELECT * FROM HEALTHCARE.STAGING.STG_CLAIMS LIMIT 10;