USE ROLE ACCOUNTADMIN;
USE WAREHOUSE HEALTHCARE_WH;
USE DATABASE HEALTHCARE;

-- 1. Create the Analytics (Marts) Schema
CREATE SCHEMA IF NOT EXISTS HEALTHCARE.MARTS;

-- 2. Dimension Table: Unique Healthcare Providers
CREATE OR REPLACE TABLE HEALTHCARE.MARTS.DIM_PROVIDERS AS
SELECT DISTINCT
    PROVIDER_NAME
FROM HEALTHCARE.STAGING.STG_CLAIMS
WHERE PROVIDER_NAME IS NOT NULL;

-- 3. Dimension Table: Insurance Plans split by Tier and Network Type
CREATE OR REPLACE TABLE HEALTHCARE.MARTS.DIM_PLANS AS
SELECT DISTINCT
    INSURANCE_PLAN,
    SPLIT_PART(INSURANCE_PLAN, '_', 1) AS PLAN_TIER,
    SPLIT_PART(INSURANCE_PLAN, '_', 2) AS NETWORK_TYPE
FROM HEALTHCARE.STAGING.STG_CLAIMS
WHERE INSURANCE_PLAN IS NOT NULL;

-- 4. Fact Table: All Claims with Automated Fraud & Leakage Flags
CREATE OR REPLACE TABLE HEALTHCARE.MARTS.FACT_CLAIMS AS
WITH benchmarked_claims AS (
    SELECT
        *,
        -- Standard median charge per procedure to detect upcoding outliers
        MEDIAN(CHARGE_AMOUNT) OVER (PARTITION BY PROCEDURE_CODE) AS MEDIAN_PROCEDURE_RATE,

        -- Sequence number to catch duplicate claim submissions
        ROW_NUMBER() OVER (
            PARTITION BY PATIENT_ID, PROCEDURE_CODE, DATE_OF_SERVICE
            ORDER BY SUBMITTED_DATE, CLAIM_ID
        ) AS DUPLICATE_SEQ
    FROM HEALTHCARE.STAGING.STG_CLAIMS
)
SELECT
    CLAIM_ID,
    PATIENT_ID,
    POLICY_NUMBER,
    INSURANCE_PLAN,
    PROVIDER_NAME,
    DIAGNOSIS_CODE,
    DIAGNOSIS_DESC,
    PROCEDURE_CODE,
    PROCEDURE_DESC,
    DATE_OF_SERVICE,
    SUBMITTED_DATE,
    SUBMISSION_LAG_DAYS,
    CHARGE_AMOUNT,
    MEDIAN_PROCEDURE_RATE,

    -- Flag 1: Upcoding Outlier (Charged > 2x the standard procedure median)
    CASE WHEN CHARGE_AMOUNT > (MEDIAN_PROCEDURE_RATE * 2) THEN 1 ELSE 0 END AS IS_UPCODING_FLAG,

    -- Flag 2: Timely Filing Violation (Submitted > 90 days after service date)
    CASE WHEN SUBMISSION_LAG_DAYS > 90 THEN 1 ELSE 0 END AS IS_LATE_FILING_FLAG,

    -- Flag 3: Clinical Mismatch (Routine exam Z00.00 billed with major knee surgery 27447)
    CASE WHEN DIAGNOSIS_CODE = 'Z00.00' AND PROCEDURE_CODE = '27447' THEN 1 ELSE 0 END AS IS_CLINICAL_MISMATCH_FLAG,

    -- Flag 4: Duplicate Claim Submission
    CASE WHEN DUPLICATE_SEQ > 1 THEN 1 ELSE 0 END AS IS_DUPLICATE_FLAG,

    -- Master Anomaly Flag (1 if any fraud/leakage rule triggered)
    CASE
        WHEN CHARGE_AMOUNT > (MEDIAN_PROCEDURE_RATE * 2)
          OR SUBMISSION_LAG_DAYS > 90
          OR (DIAGNOSIS_CODE = 'Z00.00' AND PROCEDURE_CODE = '27447')
          OR DUPLICATE_SEQ > 1
        THEN 1 ELSE 0
    END AS IS_ANY_ANOMALY,

    -- Estimated Preventable Financial Leakage ($)
    CASE
        WHEN DUPLICATE_SEQ > 1 THEN CHARGE_AMOUNT
        WHEN CHARGE_AMOUNT > (MEDIAN_PROCEDURE_RATE * 2) THEN (CHARGE_AMOUNT - MEDIAN_PROCEDURE_RATE)
        WHEN DIAGNOSIS_CODE = 'Z00.00' AND PROCEDURE_CODE = '27447' THEN CHARGE_AMOUNT
        ELSE 0
    END AS LEAKAGE_AMOUNT
FROM benchmarked_claims;

-- 5. Summary Mart: Hospital Risk Scorecard for Power BI
CREATE OR REPLACE TABLE HEALTHCARE.MARTS.MART_PROVIDER_RISK AS
SELECT
    PROVIDER_NAME,
    COUNT(CLAIM_ID) AS TOTAL_CLAIMS,
    SUM(CHARGE_AMOUNT) AS TOTAL_CHARGED_AMOUNT,
    SUM(IS_ANY_ANOMALY) AS TOTAL_FLAGGED_CLAIMS,
    ROUND(SUM(IS_ANY_ANOMALY) * 100.0 / COUNT(CLAIM_ID), 2) AS ANOMALY_RATE_PCT,
    SUM(IS_UPCODING_FLAG) AS UPCODING_CLAIMS,
    SUM(IS_LATE_FILING_FLAG) AS LATE_FILING_CLAIMS,
    SUM(IS_CLINICAL_MISMATCH_FLAG) AS MISMATCH_CLAIMS,
    SUM(IS_DUPLICATE_FLAG) AS DUPLICATE_CLAIMS,
    ROUND(SUM(LEAKAGE_AMOUNT), 2) AS TOTAL_LEAKAGE_DOLLARS
FROM HEALTHCARE.MARTS.FACT_CLAIMS
GROUP BY PROVIDER_NAME
ORDER BY TOTAL_LEAKAGE_DOLLARS DESC;

-- 6. Preview the Final Hospital Risk Summary Table
SELECT * FROM HEALTHCARE.MARTS.MART_PROVIDER_RISK;
