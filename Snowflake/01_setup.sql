USE ROLE ACCOUNTADMIN;


CREATE WAREHOUSE IF NOT EXISTS HEALTHCARE_WH
 WAREHOUSE_SIZE = 'X-SMALL'
 AUTO_SUSPEND = 60
 AUTO_RESUME = TRUE
 INITIALLY_SUSPENDED = TRUE

CREATE DATABASE IF NOT EXISTS HEALTHCARE;
CREATE SCHEMA IF NOT EXISTS HEALTHCARE.BRONZE;
CREATE SCHEMA IF NOT EXISTS HEALTHCARE.RAW;
CREATE SCHEMA IF NOT EXISTS HEALTHCARE.STAGING;
CREATE SCHEMA IF NOT EXISTS HEALTHCARE.MARTS;
CREATE SCHEMA IF NOT EXISTS HEALTHCARE.SNAPSHOTS;
CREATE SCHEMA IF NOT EXISTS HEALTHCARE.AI;

CREATE ROLE IF NOT EXISTS DBT_ROLE;
GRANT USAGE ON WAREHOUSE HEALTHCARE_WH TO ROLE DBT_ROLE;
GRANT OPERATE ON WAREHOUSE HEALTHCARE_WH TO ROLE DBT_ROLE;
GRANT ALL ON DATABASE HEALTHCARE TO ROLE DBT_ROLE;
GRANT ALL ON ALL SCHEMAS IN DATABASE HEALTHCARE TO ROLE DBT_ROLE;
GRANT ALL ON FUTURE SCHEMAS IN DATABASE HEALTHCARE TO ROLE DBT_ROLE;
GRANT ALL ON FUTURE TABLES IN DATABASE HEALTHCARE TO ROLE DBT_ROLE;
GRANT ALL ON FUTURE VIEWS IN DATABASE HEALTHCARE TO ROLE DBT_ROLE;

SET my_user = CURRENT_USER();
GRANT ROLE DBT_ROLE TO USER IDENTIFIER($my_user);

SELECT 'setup complete' AS STATUS;
